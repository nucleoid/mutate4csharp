using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Mutate4CSharp.Tests;

public sealed class ResolvedGraphCandidateAdmissionTests
{
    private const string PathName = "src/App.cs";
    private const string Source = "// \u00e9\r\npublic static class App\r\n{\r\n    public static bool First() => true;\r\n    public static bool Second() => false;\r\n}\r\n";
    private static CheckConfiguration Configuration(string root) => new("2", root,
        [new("app", "src/App.csproj", "net10.0", "actual", "14.0", null, [], ["src/**/*.cs"], [], ["suite"]) { Configuration = "Release" }],
        [new("suite", "tests/Suite.csproj", "vstest", "net10.0", "Release", ["Suite.dll"])], [],
        [new("src/Excluded.cs", "fixture exclusion")], new(1, 100, 60, 60, 120, false, 1));
    private static ScopePlan Scope(string root, bool changed = false)
    {
        var declarations = DeclarationCatalog.Compare(PathName, null, Encoding.UTF8.GetBytes(Source)).Declarations;
        return new("1", "inputs", root, null,
            [new(PathName, null, ChangeKind.Explicit, changed ? declarations.Where(d => d.DisplayName.Contains("First", StringComparison.Ordinal)).ToArray() : declarations, [], false, [])], [],
            [new("src/App.csproj", ["tests/Suite.csproj"], [PathName], changed ? "CHANGED_DECLARATIONS" : "FULL_PROJECT")], [], true);
    }
    private static MutationCandidate Candidate(string path = PathName, string text = Source, bool second = false)
    {
        var original = second ? "false" : "true";
        var start = text.IndexOf(original, StringComparison.Ordinal); var span = new TextSpan(start, original.Length);
        var tree = CSharpSyntaxTree.ParseText(text); var identified = MutationIdentity.Create(path, tree.GetRoot(), span, "bool", "1", second ? "true" : "false");
        var lines = tree.GetLineSpan(span);
        return new(identified.MutationId, EvaluationUnitIdentity.Compute(new(identified.MutationId, "src/App.csproj", "net10.0", "actual")),
            identified.Material, "src/App.csproj", "net10.0", "actual", start, original.Length, original,
            lines.StartLinePosition.Line + 1, lines.StartLinePosition.Character + 1, lines.EndLinePosition.Line + 1, lines.EndLinePosition.Character + 1);
    }
    private static void Write(SnapshotTestRepository repository, byte[]? source = null)
    {
        repository.Write(PathName, source ?? Encoding.UTF8.GetBytes(Source));
        repository.WriteText("src/Other.cs", Source); repository.WriteText("outside/Other.cs", Source);
        repository.WriteText("src/Excluded.cs", Source); repository.WriteText("src/tests/Test.cs", Source);
        repository.WriteText("src/Generated.cs", "// <auto-generated/>\n" + Source);
        repository.WriteText("Mutate4CSharp.json", "{}"); repository.Git("add", "."); repository.Git("commit", "-m", "parent source admission");
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task Actual_snapshot_bytes_and_physical_positions_admit_UTF8_and_BOM_UTF16_without_fresh_original(bool utf16)
    {
        using var repository = new SnapshotTestRepository();
        Write(repository, utf16 ? Encoding.Unicode.GetPreamble().Concat(Encoding.Unicode.GetBytes(Source)).ToArray() : Encoding.UTF8.GetBytes(Source));
        await using var snapshot = await SnapshotCapture.CaptureAsync(repository.Root, "HEAD", [], SnapshotCaptureOptions.Default, TestContext.Current.CancellationToken);
        var original = new ResolvedGraphBudget(TimeSpan.FromSeconds(30), TestContext.Current.CancellationToken);
        using var inputs = new ResolvedGraphInputs(original);
        ResolvedGraphCandidateAdmission.Validate(snapshot, Configuration(repository.Root), Scope(repository.Root, true), [Candidate()], inputs);
        Assert.Equal("Mutate4CSharp.json", ResolvedGraphCandidateAdmission.ConfigurationFile(snapshot).RelativePath);
        Assert.Null(original.Observe().Cleanup);
    }

    [Theory]
    [InlineData("glob")]
    [InlineData("excluded")]
    [InlineData("test")]
    [InlineData("generated")]
    [InlineData("uncaptured")]
    [InlineData("scope")]
    [InlineData("scope-excluded")]
    [InlineData("declaration")]
    [InlineData("project")]
    [InlineData("framework")]
    [InlineData("parse")]
    [InlineData("start")]
    [InlineData("length")]
    [InlineData("original")]
    [InlineData("line")]
    [InlineData("column")]
    [InlineData("end-line")]
    [InlineData("end-column")]
    [InlineData("material")]
    public async Task Malformed_worker_data_refuses_before_coverage_can_complete_an_uncovered_unit(string changed)
    {
        using var repository = new SnapshotTestRepository(); Write(repository);
        await using var snapshot = await SnapshotCapture.CaptureAsync(repository.Root, "HEAD", [], SnapshotCaptureOptions.Default, TestContext.Current.CancellationToken);
        using var inputs = new ResolvedGraphInputs(new ResolvedGraphBudget(TimeSpan.FromSeconds(30), TestContext.Current.CancellationToken));
        var candidate = changed switch {
            "glob" => Candidate("outside/Other.cs"), "excluded" => Candidate("src/Excluded.cs"), "test" => Candidate("src/tests/Test.cs"),
            "generated" => Candidate("src/Generated.cs", "// <auto-generated/>\n" + Source), "uncaptured" => Candidate("src/obj/GeneratedFixture.cs"),
            "scope" => Candidate("src/Other.cs"), "scope-excluded" => Candidate(), "declaration" => Candidate(second: true),
            "project" => Candidate() with { ProjectPath = "src/Other.csproj" }, "framework" => Candidate() with { TargetFramework = "net9.0" },
            "parse" => Candidate() with { ParseContext = "foreign" }, "start" => Candidate() with { SourceStart = int.MaxValue },
            "length" => Candidate() with { SourceLength = int.MaxValue }, "original" => Candidate() with { Original = "xxxx" },
            "line" => Candidate() with { SourceLine = 1 }, "column" => Candidate() with { SourceColumn = 1 },
            "end-line" => Candidate() with { SourceEndLine = 1 }, "end-column" => Candidate() with { SourceEndColumn = 1 },
            "material" => Candidate() with { Material = null! }, _ => throw new ArgumentException(changed) };
        var scope = Scope(repository.Root, changed is "scope" or "declaration");
        if (changed == "scope-excluded") scope = scope with { Exclusions = [new(PathName, "fixture", "parent excluded", false)] };
        Assert.Throws<EvaluationContractException>(() => ResolvedGraphCandidateAdmission.Validate(snapshot, Configuration(repository.Root), scope, [candidate], inputs));
    }

    [Fact]
    public async Task Missing_captured_configuration_is_a_typed_refusal()
    {
        using var repository = new SnapshotTestRepository();
        repository.WriteText(PathName, Source); repository.Git("add", "."); repository.Git("commit", "-m", "missing config");
        await using var snapshot = await SnapshotCapture.CaptureAsync(repository.Root, "HEAD", [], SnapshotCaptureOptions.Default, TestContext.Current.CancellationToken);
        Assert.Throws<EvaluationContractException>(() => ResolvedGraphCandidateAdmission.ConfigurationFile(snapshot));
    }

    [Fact]
    public async Task Parent_refuses_changed_capture_bytes_even_when_worker_span_matches_the_changed_text()
    {
        using var repository = new SnapshotTestRepository(); Write(repository);
        await using var snapshot = await SnapshotCapture.CaptureAsync(repository.Root, "HEAD", [], SnapshotCaptureOptions.Default, TestContext.Current.CancellationToken);
        File.AppendAllText(System.IO.Path.Combine(snapshot.CaptureRoot, PathName), "// drift");
        using var inputs = new ResolvedGraphInputs(new ResolvedGraphBudget(TimeSpan.FromSeconds(30), TestContext.Current.CancellationToken));
        Assert.Throws<SnapshotDivergedException>(() => ResolvedGraphCandidateAdmission.Validate(snapshot, Configuration(repository.Root), Scope(repository.Root), [Candidate()], inputs));
    }

    [Fact]
    public void Worker_request_omits_255_unused_contexts_but_preserves_the_complete_selected_record_and_finite_limits()
    {
        var configuration = Configuration(System.IO.Path.GetTempPath());
        var selected = new ResolvedProjectCapture(new("src/App.csproj", "net10.0", "Release"),
            new Dictionary<string, string> { ["completeMetadata"] = new('x', 4096) }, new Dictionary<string, IReadOnlyList<ResolvedGraphItem>>(), [], new('0', 64));
        var all = Enumerable.Range(0, ResolvedGraphCapture.MaxContexts).Select(i => i == 0 ? selected : selected with {
            Selection = new("tests/Unused" + i + ".csproj", "net10.0", "Release") }).ToArray();
        var actual = ResolvedGraphCandidateAdmission.ProductionContexts(configuration, all);
        Assert.Same(selected, Assert.Single(actual));
        var completeBytes = JsonSerializer.SerializeToUtf8Bytes(all, ResolvedGraphProtocol.Options).Length;
        var selectedBytes = JsonSerializer.SerializeToUtf8Bytes(actual, ResolvedGraphProtocol.Options).Length;
        Assert.True(completeBytes > selectedBytes * 200);
        TestContext.Current.TestOutputHelper?.WriteLine($"Context-only DATA bytes: all256={completeBytes}, selected1={selectedBytes}; actual request16MiB/result32MiB and262144-node limits remain unchanged. Full Forge fit is unproven.");
        Assert.Throws<EvaluationContractException>(() => ResolvedGraphCandidateAdmission.ProductionContexts(configuration, []));
        Assert.Throws<EvaluationContractException>(() => ResolvedGraphCandidateAdmission.ProductionContexts(configuration, [selected, selected]));
    }
}
